"""MSG91 OTP delivery and verification for customer authentication."""
import os

import requests

from app.phone_utils import to_e164

MSG91_BASE_URL = "https://control.msg91.com/api/v5/otp"
REQUEST_TIMEOUT_SECONDS = 10


def _credentials() -> tuple[str, str]:
    authkey = os.getenv("MSG91_AUTHKEY")
    template_id = os.getenv("MSG91_TEMPLATE_ID")
    if not authkey or not template_id:
        raise RuntimeError("MSG91 OTP is not configured. Set MSG91_AUTHKEY and MSG91_TEMPLATE_ID.")
    return authkey, template_id


def send_otp(phone: str) -> dict:
    """Ask MSG91 to generate and send an OTP for the supplied mobile number."""
    authkey, template_id = _credentials()
    response = requests.post(
        MSG91_BASE_URL,
        params={"template_id": template_id, "mobile": to_e164(phone)},
        headers={"authkey": authkey, "content-type": "application/json"},
        timeout=REQUEST_TIMEOUT_SECONDS,
    )
    try:
        payload = response.json()
    except ValueError:
        payload = {"message": response.text}

    if response.status_code >= 400 or str(payload.get("type", "")).lower() not in {"success", "successfull"}:
        raise RuntimeError(f"MSG91 OTP send failed: {payload.get('message', 'provider error')}")
    return payload


def verify_otp(phone: str, otp: str) -> bool:
    """Verify the OTP generated by MSG91 for the supplied mobile number."""
    authkey, _ = _credentials()
    response = requests.get(
        f"{MSG91_BASE_URL}/verify",
        params={"otp": otp, "mobile": to_e164(phone)},
        headers={"authkey": authkey},
        timeout=REQUEST_TIMEOUT_SECONDS,
    )
    try:
        payload = response.json()
    except ValueError:
        payload = {"message": response.text}

    if response.status_code >= 400:
        return False
    return str(payload.get("type", "")).lower() in {"success", "successfull"}
